// Use meaningful examples to demonstrate each concept.

// Let
let age = 20

// Const
const name = "Mohit"

// Variable Decelaration 
let name1;

// Variable Assignment
name1 = "Rohit"

// String data type
let skill = "Web Development";

console.log("Skill:", skill);
console.log("Skill Type:", typeof skill);


// Number data type
let projects = 5;

console.log("Projects:", projects);
console.log("Projects Type:", typeof projects);


// Boolean data type
let isLearning = true;

console.log("Is Learning:", isLearning);
console.log("Is Learning type:", typeof isLearning);


// Undefined data type
let futureJob;

console.log("Future Job:", futureJob);
console.log("Future Job type:", typeof futureJob);


// Null value
let currentProject = null;

console.log("Current Project:", currentProject);
console.log("Current Project type:", typeof currentProject);